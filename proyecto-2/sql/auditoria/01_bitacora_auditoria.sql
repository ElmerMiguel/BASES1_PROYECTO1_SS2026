SET search_path TO hospitales_occidente, public;
SET timezone TO 'America/Guatemala';

-- Tabla para registro de auditoria de cambios sensibles en personal
CREATE TABLE IF NOT EXISTS bitacora_auditoria_personal (
    id_auditoria     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_personal      INTEGER      NOT NULL,
    tabla_afectada   VARCHAR(50)  NOT NULL,
    campo_modificado VARCHAR(50)  NOT NULL,
    valor_anterior   TEXT,
    valor_nuevo      TEXT,
    usuario_db       VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    fecha_hora       TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    operacion        VARCHAR(10)  NOT NULL DEFAULT 'UPDATE',
    CONSTRAINT pk_bitacora_auditoria PRIMARY KEY (id_auditoria),
    CONSTRAINT fk_bitacora_personal FOREIGN KEY (id_personal)
        REFERENCES personal (id_personal) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_bitacora_personal ON bitacora_auditoria_personal (id_personal);
CREATE INDEX IF NOT EXISTS ix_bitacora_fecha ON bitacora_auditoria_personal (fecha_hora);

-- Permisos para roles
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rol_auditor_consulta') THEN
        GRANT SELECT ON TABLE bitacora_auditoria_personal TO rol_auditor_consulta;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rol_admin_hospital') THEN
        GRANT ALL ON TABLE bitacora_auditoria_personal TO rol_admin_hospital;
    END IF;
END $$;
