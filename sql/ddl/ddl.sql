-- Vista analítica de pacientes con cálculo dinámico de edad en años cumplidos.
CREATE OR REPLACE VIEW vw_paciente AS
SELECT 
    pa.id_paciente,
    pa.no_expediente,
    pe.nombres,
    pe.apellidos,
    pe.dpi,
    pe.sexo,
    pe.fecha_nacimiento,
    EXTRACT(YEAR FROM age(CURRENT_DATE, pe.fecha_nacimiento))::INTEGER AS edad_anios,
    pa.estado_civil,
    pe.telefono,
    di.area,
    di.detalle AS direccion_completa,
    mu.nombre AS municipio,
    de.nombre AS departamento
FROM paciente pa
JOIN persona      pe ON pe.id_persona      = pa.id_persona
JOIN direccion    di ON di.id_direccion    = pe.id_direccion
JOIN municipio    mu ON mu.id_municipio    = di.id_municipio
JOIN departamento de ON de.id_departamento = mu.id_departamento;

-- Cálculo de días de internamiento por egreso (mínimo 1 día para fines tarifarios).
CREATE OR REPLACE VIEW vw_egreso_dias AS
SELECT 
    eg.id_egreso,
    ing.id_ingreso,
    ing.id_episodio,
    tu.nombre AS unidad,
    ing.fecha_hora_ingreso,
    eg.fecha_hora_egreso,
    GREATEST(1, CEIL(EXTRACT(EPOCH FROM (eg.fecha_hora_egreso - ing.fecha_hora_ingreso)) / 86400))::INTEGER AS dias_hospitalizado
FROM egreso eg
JOIN ingreso         ing ON ing.id_ingreso        = eg.id_ingreso
JOIN unidad_hospital uh  ON uh.id_unidad_hospital = ing.id_unidad_hospital
JOIN tipo_unidad     tu  ON tu.id_tipo_unidad     = uh.id_tipo_unidad;

-- Estado financiero de facturas con total facturado, total amortizado y saldo insoluto.
CREATE OR REPLACE VIEW vw_factura_resumen AS
SELECT 
    f.id_factura,
    f.serie,
    f.numero_factura,
    f.id_episodio,
    f.numero_cuotas,
    f.estado,
    COALESCE(t.total, 0.00)                                   AS total_facturado,
    COALESCE(p.pagado, 0.00)                                  AS total_pagado,
    ROUND(COALESCE(t.total, 0.00) - COALESCE(p.pagado, 0.00), 2) AS saldo_pendiente
FROM factura f
LEFT JOIN (
    SELECT 
        id_factura,
        ROUND(SUM(cantidad * precio_unitario * (porcentaje_aplicado / 100.0)), 2) AS total
    FROM factura_detalle
    GROUP BY id_factura
) t ON t.id_factura = f.id_factura
LEFT JOIN (
    SELECT 
        id_factura,
        ROUND(SUM(monto), 2) AS pagado
    FROM pago
    GROUP BY id_factura
) p ON p.id_factura = f.id_factura;

-- Reporte de cirugías rechazadas por el comité médico con facultativo y justificación.
CREATE OR REPLACE VIEW vw_cirugias_rechazadas AS
SELECT 
    r.id_revision,
    s.id_solicitud_cirugia,
    s.id_episodio,
    ep.id_paciente,
    s.id_cirujano,
    pe.nombres || ' ' || pe.apellidos AS cirujano,
    s.caracter,
    r.fecha_hora                      AS fecha_revision,
    r.razones                         AS motivo_rechazo
FROM revision_solicitud r
JOIN solicitud_cirugia s  ON s.id_solicitud_cirugia = r.id_solicitud_cirugia
JOIN episodio         ep  ON ep.id_episodio         = s.id_episodio
JOIN personal         pl  ON pl.id_personal         = s.id_cirujano
JOIN persona          pe  ON pe.id_persona          = pl.id_persona
WHERE r.decision = 'Rechazada';

-- Resumen de satisfacción y calificación media obtenida por cada hospital.
CREATE OR REPLACE VIEW vw_calificacion_resumen_hospital AS
SELECT 
    h.id_hospital,
    h.nombre AS hospital,
    COUNT(ch.id_calificacion_hospital) AS total_evaluaciones,
    ROUND(AVG(ch.puntuacion), 2)       AS promedio_estrellas
FROM hospital h
LEFT JOIN episodio ep ON ep.id_hospital = h.id_hospital
LEFT JOIN calificacion_hospital ch ON ch.id_episodio = ep.id_episodio
WHERE h.es_interno = TRUE
GROUP BY h.id_hospital, h.nombre;


