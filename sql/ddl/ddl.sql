    CONSTRAINT ck_cita_estado            CHECK (estado IN ('Programada', 'Realizada', 'Reprogramada', 'Cancelada')),  -- estados validos de gestion de la cita
    CONSTRAINT ck_cita_referente         CHECK ((tipo_consulta = 'Referido' AND id_hospital_referente IS NOT NULL) OR (tipo_consulta <> 'Referido' AND id_hospital_referente IS NULL)),  -- centro remitente requerido exclusivamente para pacientes referidos
