    CONSTRAINT ck_signos_talla      CHECK (talla_cm IS NULL OR talla_cm BETWEEN 20.0 AND 250.0),  -- estatura corporal razonable en centimetros
    CONSTRAINT fk_signos_episodio FOREIGN KEY (id_episodio)
