    canal_asignacion       VARCHAR(20)  NOT NULL,
    tipo_consulta          VARCHAR(12)  NOT NULL,
    id_hospital_referente  INTEGER,
    estado                 VARCHAR(13)  NOT NULL DEFAULT 'Programada',
    fecha_cancelacion      TIMESTAMPTZ,
    motivo_cancelacion     VARCHAR(200),
    cancelacion_notificada BOOLEAN,
    id_cita_anterior       BIGINT,
    id_cita_recargo_origen BIGINT,
    creada_en              TIMESTAMPTZ  NOT NULL DEFAULT now(),
