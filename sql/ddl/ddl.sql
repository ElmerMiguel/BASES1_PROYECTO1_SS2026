/* ============================================================================
   M1. CATÁLOGOS CLÍNICOS Y GEOGRAFÍA (19 TABLAS)
   ============================================================================ */

-- Departamentos de la república de Guatemala.
CREATE TABLE departamento (
    id_departamento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(50) NOT NULL,
    CONSTRAINT pk_departamento        PRIMARY KEY (id_departamento),
    CONSTRAINT uq_departamento_nombre UNIQUE (nombre),
    CONSTRAINT ck_departamento_nombre CHECK (length(trim(nombre)) >= 3)  -- nombre de departamento no vacio
);

-- Municipios pertenecientes a cada departamento.
CREATE TABLE municipio (
    id_municipio    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_departamento INTEGER     NOT NULL,
    nombre          VARCHAR(80) NOT NULL,
    CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
    CONSTRAINT uq_municipio_nombre UNIQUE (id_departamento, nombre),
    CONSTRAINT ck_municipio_nombre CHECK (length(trim(nombre)) >= 2),  -- nombre de municipio no vacio
    CONSTRAINT fk_municipio_departamento FOREIGN KEY (id_departamento)
        REFERENCES departamento (id_departamento) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Dirección habitual reutilizable por personas e instalaciones hospitalarias.
CREATE TABLE direccion (
    id_direccion INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_municipio INTEGER      NOT NULL,
    area         VARCHAR(7)   NOT NULL,
    detalle      VARCHAR(200) NOT NULL,
    CONSTRAINT pk_direccion       PRIMARY KEY (id_direccion),
    CONSTRAINT ck_direccion_area  CHECK (area IN ('Urbana', 'Rural')),  -- clasificacion de area urbana o rural
    CONSTRAINT ck_direccion_det   CHECK (length(trim(detalle)) >= 5),  -- detalle descriptivo suficiente
    CONSTRAINT fk_direccion_municipio FOREIGN KEY (id_municipio)
        REFERENCES municipio (id_municipio) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Catálogo de parentescos reconocidos entre paciente y encargado legal.
CREATE TABLE parentesco (
    id_parentesco INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR(40) NOT NULL,
    CONSTRAINT pk_parentesco        PRIMARY KEY (id_parentesco),
    CONSTRAINT uq_parentesco_nombre UNIQUE (nombre),
    CONSTRAINT ck_parentesco_nombre CHECK (length(trim(nombre)) >= 3)  -- nombre de parentesco valido
);

-- Especialidades médicas clínicas y quirúrgicas avaladas por la institución.
CREATE TABLE especialidad (
    id_especialidad INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(80) NOT NULL,
    tipo            VARCHAR(10) NOT NULL,
    CONSTRAINT pk_especialidad        PRIMARY KEY (id_especialidad),
    CONSTRAINT uq_especialidad_nombre UNIQUE (nombre),
    CONSTRAINT ck_especialidad_tipo   CHECK (tipo IN ('Clinica', 'Quirurgica'))  -- clasificacion clinica o quirurgica
);

-- Catálogo de diagnósticos médicos codificados según estándar CIE-10.
CREATE TABLE diagnostico (
    id_diagnostico INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo_cie10   VARCHAR(10)  NOT NULL,
    descripcion    VARCHAR(250) NOT NULL,
    CONSTRAINT pk_diagnostico        PRIMARY KEY (id_diagnostico),
    CONSTRAINT uq_diagnostico_codigo UNIQUE (codigo_cie10),
    CONSTRAINT ck_diagnostico_codigo CHECK (codigo_cie10 ~ '^[A-Z][0-9]{2}(\.[0-9]{1,2})?$')  -- formato estandar de codigo CIE-10
);

-- Tipos de unidad médica de atención y destino.
CREATE TABLE tipo_unidad (
    id_tipo_unidad INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(30) NOT NULL,
    CONSTRAINT pk_tipo_unidad        PRIMARY KEY (id_tipo_unidad),
    CONSTRAINT uq_tipo_unidad_nombre UNIQUE (nombre),
    CONSTRAINT ck_tipo_unidad_nombre CHECK (nombre IN ('Consulta externa', 'Emergencias', 'Cirugia', 'Hospitalizacion', 'Otro'))  -- unidades medicas oficiales y destinos externos
);

-- Servicios y especialidades asistenciales ofrecidos en cada unidad.
CREATE TABLE servicio_medico (
    id_servicio    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_tipo_unidad INTEGER      NOT NULL,
    nombre         VARCHAR(100) NOT NULL,
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_servicio_medico        PRIMARY KEY (id_servicio),
    CONSTRAINT uq_servicio_medico_nombre UNIQUE (id_tipo_unidad, nombre),
    CONSTRAINT ck_servicio_medico_nombre CHECK (length(trim(nombre)) >= 3),  -- nombre de servicio asistencial valido
    CONSTRAINT fk_servicio_tipo_unidad FOREIGN KEY (id_tipo_unidad)
        REFERENCES tipo_unidad (id_tipo_unidad) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Turnos laborales de atención médica y guardias.
CREATE TABLE turno (
    id_turno    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(40) NOT NULL,
    hora_inicio TIME        NOT NULL,
    hora_fin    TIME        NOT NULL,
    CONSTRAINT pk_turno        PRIMARY KEY (id_turno),
    CONSTRAINT uq_turno_nombre UNIQUE (nombre),
    CONSTRAINT ck_turno_horas  CHECK (hora_inicio <> hora_fin)  -- turno laboral con duracion mayor a cero
);

-- Métodos de pago autorizados en recepción y cajas de cobro.
CREATE TABLE metodo_pago (
    id_metodo_pago INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(30) NOT NULL,
    CONSTRAINT pk_metodo_pago        PRIMARY KEY (id_metodo_pago),
    CONSTRAINT uq_metodo_pago_nombre UNIQUE (nombre),
    CONSTRAINT ck_metodo_pago_nombre CHECK (length(trim(nombre)) >= 3)  -- descripcion de metodo de pago valida
);

-- Catálogo de medicamentos recetables con su presentación farmacéutica.
CREATE TABLE medicamento (
    id_medicamento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(120) NOT NULL,
    presentacion   VARCHAR(80),
    CONSTRAINT pk_medicamento        PRIMARY KEY (id_medicamento),
    CONSTRAINT uq_medicamento_nombre UNIQUE (nombre, presentacion),
    CONSTRAINT ck_medicamento_nombre CHECK (length(trim(nombre)) >= 2)  -- nombre de medicamento valido
);

-- Catálogo de pruebas diagnósticas y análisis clínicos de laboratorio.
CREATE TABLE examen_laboratorio (
    id_examen INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre    VARCHAR(120) NOT NULL,
    CONSTRAINT pk_examen_laboratorio        PRIMARY KEY (id_examen),
    CONSTRAINT uq_examen_laboratorio_nombre UNIQUE (nombre),
    CONSTRAINT ck_examen_lab_nombre         CHECK (length(trim(nombre)) >= 3)  -- nombre de examen diagnostico valido
);

-- Tipos de anestesia administrables en procedimientos quirúrgicos.
CREATE TABLE tipo_anestesia (
    id_tipo_anestesia INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(50) NOT NULL,
    CONSTRAINT pk_tipo_anestesia        PRIMARY KEY (id_tipo_anestesia),
    CONSTRAINT uq_tipo_anestesia_nombre UNIQUE (nombre),
    CONSTRAINT ck_tipo_anestesia_nombre CHECK (length(trim(nombre)) >= 3)  -- tipo de tecnica anestesica valida
);

-- Procedimientos quirúrgicos clasificados por especialidad médica.
CREATE TABLE procedimiento_quirurgico (
    id_procedimiento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_especialidad  INTEGER      NOT NULL,
    nombre           VARCHAR(150) NOT NULL,
    descripcion      VARCHAR(300),
    CONSTRAINT pk_procedimiento_quirurgico        PRIMARY KEY (id_procedimiento),
    CONSTRAINT uq_procedimiento_quirurgico_nombre UNIQUE (nombre),
    CONSTRAINT ck_proc_quirurgico_nombre          CHECK (length(trim(nombre)) >= 4),  -- nombre de intervencion quirurgica valida
    CONSTRAINT fk_procedimiento_especialidad FOREIGN KEY (id_especialidad)
        REFERENCES especialidad (id_especialidad) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Insumos consumibles y materiales quirúrgicos utilizados en la atención.
CREATE TABLE insumo (
    id_insumo   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(120) NOT NULL,
    descripcion VARCHAR(300),
    material    VARCHAR(80),
    tipo        VARCHAR(10)  NOT NULL,
    CONSTRAINT pk_insumo        PRIMARY KEY (id_insumo),
    CONSTRAINT uq_insumo_nombre UNIQUE (nombre),
    CONSTRAINT ck_insumo_tipo   CHECK (tipo IN ('Medico', 'Quirurgico', 'Otro'))  -- clasificacion oficial del tipo de insumo
);

-- Instrumental quirúrgico reutilizable y su función operativa.
CREATE TABLE instrumento (
    id_instrumento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(120) NOT NULL,
    descripcion    VARCHAR(300),
    tipo           VARCHAR(10)  NOT NULL,
    funcion        VARCHAR(12)  NOT NULL,
    CONSTRAINT pk_instrumento        PRIMARY KEY (id_instrumento),
    CONSTRAINT uq_instrumento_nombre UNIQUE (nombre),
    CONSTRAINT ck_instrumento_tipo    CHECK (tipo IN ('Medico', 'Quirurgico', 'Otro')),  -- clasificacion de instrumento medico o quirurgico
    CONSTRAINT ck_instrumento_funcion CHECK (funcion IN ('Corte', 'Contenido', 'Hemostatica', 'Retractor', 'Accesorio', 'Implante', 'Otro'))  -- funcion quirurgica del instrumental
);

-- Equipos biomédicos y electromédicos asignables.
CREATE TABLE equipo (
    id_equipo   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(120) NOT NULL,
    descripcion VARCHAR(300),
    tipo        VARCHAR(10)  NOT NULL,
    funcion     VARCHAR(15)  NOT NULL,
    CONSTRAINT pk_equipo        PRIMARY KEY (id_equipo),
    CONSTRAINT uq_equipo_nombre UNIQUE (nombre),
    CONSTRAINT ck_equipo_tipo    CHECK (tipo IN ('Medico', 'Quirurgico', 'Otro')),  -- clasificacion del equipo medico o quirurgico
    CONSTRAINT ck_equipo_funcion CHECK (funcion IN ('Exploracion', 'Diagnostico', 'Tratamiento', 'Rehabilitacion', 'Otro'))  -- funcion asistencial del equipo
);

-- Momentos de control del proceso quirúrgico según fase clínica.
CREATE TABLE momento_quirurgico (
    id_momento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR(60) NOT NULL,
    fase       VARCHAR(15) NOT NULL,
    orden      SMALLINT    NOT NULL,
    CONSTRAINT pk_momento_quirurgico        PRIMARY KEY (id_momento),
    CONSTRAINT uq_momento_quirurgico_nombre UNIQUE (nombre),
    CONSTRAINT ck_momento_fase  CHECK (fase IN ('Preoperatorio', 'Intraoperatorio', 'Postoperatorio')),  -- fase obligatoria del proceso quirurgico
    CONSTRAINT ck_momento_orden CHECK (orden > 0)  -- secuencia cronologica positiva
);

-- Ítems evaluables en los checklists de seguridad y calidad quirúrgica.
CREATE TABLE item_verificacion (
    id_item        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_momento     INTEGER      NOT NULL,
    descripcion    VARCHAR(250) NOT NULL,
    tipo_resultado VARCHAR(15)  NOT NULL,
    orden          SMALLINT     NOT NULL DEFAULT 1,
    CONSTRAINT pk_item_verificacion      PRIMARY KEY (id_item),
    CONSTRAINT uq_item_verificacion_desc UNIQUE (id_momento, descripcion),
    CONSTRAINT ck_item_tipo_resultado    CHECK (tipo_resultado IN ('Exito o fallo', 'Aceptabilidad')),  -- escala de calificacion del item
    CONSTRAINT ck_item_orden             CHECK (orden > 0),  -- orden correlativo positivo
    CONSTRAINT fk_item_momento FOREIGN KEY (id_momento)
        REFERENCES momento_quirurgico (id_momento) ON DELETE RESTRICT ON UPDATE CASCADE
);


/* ============================================================================
   M2. ESTRUCTURA HOSPITALARIA (4 TABLAS)
   ============================================================================ */

-- Hospitales pertenecientes a la red y centros externos de referencia/traslado.
CREATE TABLE hospital (
    id_hospital  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo       VARCHAR(10)  NOT NULL,
    nombre       VARCHAR(120) NOT NULL,
    id_direccion INTEGER      NOT NULL,
    telefono     VARCHAR(15),
    correo       VARCHAR(100),
    es_interno   BOOLEAN      NOT NULL DEFAULT TRUE,
    activo       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_hospital        PRIMARY KEY (id_hospital),
    CONSTRAINT uq_hospital_codigo UNIQUE (codigo),
    CONSTRAINT uq_hospital_nombre UNIQUE (nombre),
    CONSTRAINT ck_hospital_codigo   CHECK (codigo ~ '^[A-Z0-9\-]{3,10}$'),  -- formato alfanumerico de codigo hospitalario
    CONSTRAINT ck_hospital_telefono CHECK (telefono IS NULL OR telefono ~ '^(\+?502)?[0-9]{8}$'),  -- numero telefonico nacional de 8 digitos con codigo optativo
    CONSTRAINT ck_hospital_correo   CHECK (correo IS NULL OR correo ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),  -- correo electronico con formato corporativo estandar
    CONSTRAINT fk_hospital_direccion FOREIGN KEY (id_direccion)
        REFERENCES direccion (id_direccion) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Unidades asistenciales habilitadas por cada hospital interno de la red.
CREATE TABLE unidad_hospital (
    id_unidad_hospital INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_hospital        INTEGER NOT NULL,
    id_tipo_unidad     INTEGER NOT NULL,
    CONSTRAINT pk_unidad_hospital PRIMARY KEY (id_unidad_hospital),
    CONSTRAINT uq_unidad_hospital UNIQUE (id_hospital, id_tipo_unidad),
    CONSTRAINT fk_unidad_hospital FOREIGN KEY (id_hospital)
        REFERENCES hospital (id_hospital) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_unidad_tipo FOREIGN KEY (id_tipo_unidad)
        REFERENCES tipo_unidad (id_tipo_unidad) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Camillas y quirófanos habilitados físicamente en cada unidad hospitalaria.
CREATE TABLE espacio_atencion (
    id_espacio         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_unidad_hospital INTEGER     NOT NULL,
    tipo               VARCHAR(10) NOT NULL,
    codigo             VARCHAR(15) NOT NULL,
    habilitado         BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_espacio_atencion PRIMARY KEY (id_espacio),
    CONSTRAINT uq_espacio_codigo   UNIQUE (id_unidad_hospital, codigo),
    CONSTRAINT ck_espacio_tipo     CHECK (tipo IN ('Camilla', 'Quirofano')),  -- clasificacion de espacio entre camilla o quirofano
    CONSTRAINT ck_espacio_codigo   CHECK (length(trim(codigo)) >= 2),  -- identificador de espacio no vacio
    CONSTRAINT fk_espacio_unidad FOREIGN KEY (id_unidad_hospital)
        REFERENCES unidad_hospital (id_unidad_hospital) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Clínicas y consultorios físicos asignados a consulta externa en cada hospital.
CREATE TABLE clinica (
    id_clinica     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_hospital    INTEGER     NOT NULL,
    numero_clinica VARCHAR(10) NOT NULL,
    habilitada     BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_clinica        PRIMARY KEY (id_clinica),
    CONSTRAINT uq_clinica_numero UNIQUE (id_hospital, numero_clinica),
    CONSTRAINT ck_clinica_numero CHECK (length(trim(numero_clinica)) >= 1),  -- numero o nomenclatura de clinica valida
    CONSTRAINT fk_clinica_hospital FOREIGN KEY (id_hospital)
        REFERENCES hospital (id_hospital) ON DELETE RESTRICT ON UPDATE CASCADE
);


/* ============================================================================
   M3. PERSONAS Y PERSONAL (8 TABLAS)
   ============================================================================ */

-- Entidad supertipo con datos demográficos y de identificación de personas.
CREATE TABLE persona (
    id_persona       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombres          VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(100) NOT NULL,
    dpi              VARCHAR(13),
    fecha_nacimiento DATE         NOT NULL,
    sexo             VARCHAR(9)   NOT NULL,
    telefono         VARCHAR(15),
    id_direccion     INTEGER      NOT NULL,
    creado_en        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_persona            PRIMARY KEY (id_persona),
    CONSTRAINT uq_persona_dpi        UNIQUE (dpi),
    CONSTRAINT ck_persona_nombres    CHECK (length(trim(nombres)) >= 2),  -- nombres de persona validos
    CONSTRAINT ck_persona_apellidos  CHECK (length(trim(apellidos)) >= 2),  -- apellidos de persona validos
    CONSTRAINT ck_persona_dpi        CHECK (dpi IS NULL OR dpi ~ '^[0-9]{13}$'),  -- DPI guatemalteco de 13 digitos numericos
    CONSTRAINT ck_persona_sexo       CHECK (sexo IN ('Masculino', 'Femenino')),  -- clasificacion de sexo biologico
    CONSTRAINT ck_persona_nacimiento CHECK (fecha_nacimiento >= DATE '1900-01-01'),  -- fecha de nacimiento contemporanea verificable
    CONSTRAINT ck_persona_telefono   CHECK (telefono IS NULL OR telefono ~ '^(\+?502)?[0-9]{8}$'),  -- telefono de 8 digitos con codigo optativo
    CONSTRAINT fk_persona_direccion FOREIGN KEY (id_direccion)
        REFERENCES direccion (id_direccion) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Subtipo de persona correspondiente a pacientes atendidos con expediente clínico.
CREATE TABLE paciente (
    id_paciente             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_persona              INTEGER     NOT NULL,
    no_expediente           VARCHAR(20) NOT NULL,
    estado_civil            VARCHAR(15) NOT NULL DEFAULT 'Soltero',
    no_seguro_social        VARCHAR(20),
    religion                VARCHAR(50),
    ocupacion               VARCHAR(80),
    id_municipio_nacimiento INTEGER,
    CONSTRAINT pk_paciente               PRIMARY KEY (id_paciente),
    CONSTRAINT uq_paciente_persona       UNIQUE (id_persona),
    CONSTRAINT uq_paciente_expediente    UNIQUE (no_expediente),
    CONSTRAINT uq_paciente_seguro_social UNIQUE (no_seguro_social),
    CONSTRAINT ck_paciente_expediente   CHECK (length(trim(no_expediente)) >= 3),  -- numero de expediente no vacio
    CONSTRAINT ck_paciente_estado_civil CHECK (estado_civil IN ('Soltero', 'Casado', 'Divorciado', 'Viudo', 'Union de hecho')),  -- estado civil segun catalogo civil
    CONSTRAINT fk_paciente_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_paciente_municipio_nac FOREIGN KEY (id_municipio_nacimiento)
        REFERENCES municipio (id_municipio) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Relación asociativa entre pacientes y sus encargados legales/familiares (N:M).
CREATE TABLE paciente_encargado (
    id_paciente_encargado INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_paciente           INTEGER NOT NULL,
    id_persona            INTEGER NOT NULL,
    id_parentesco         INTEGER NOT NULL,
    es_principal          BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_paciente_encargado PRIMARY KEY (id_paciente_encargado),
    CONSTRAINT uq_paciente_encargado UNIQUE (id_paciente, id_persona),
    CONSTRAINT fk_pacenc_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_pacenc_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_pacenc_parentesco FOREIGN KEY (id_parentesco)
        REFERENCES parentesco (id_parentesco) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Subtipo de persona para colaboradores y empleados asistenciales/administrativos.
CREATE TABLE personal (
    id_personal   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_persona    INTEGER     NOT NULL,
    tipo_personal VARCHAR(30) NOT NULL,
    activo        BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_personal         PRIMARY KEY (id_personal),
    CONSTRAINT uq_personal_persona UNIQUE (id_persona),
    CONSTRAINT ck_personal_tipo    CHECK (tipo_personal IN ('Medico', 'Enfermero', 'Practicante de medicina', 'Practicante de enfermeria', 'Administrativo')),  -- clasificacion profesional del colaborador
    CONSTRAINT fk_personal_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Subtipo de personal para médicos con registro colegiado y régimen laboral.
CREATE TABLE medico (
    id_personal        INTEGER       NOT NULL,
    no_colegiado       VARCHAR(20)   NOT NULL,
    condicion          VARCHAR(10)   NOT NULL,
    institucion_origen VARCHAR(120),
    tarifa_consulta    NUMERIC(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT pk_medico           PRIMARY KEY (id_personal),
    CONSTRAINT uq_medico_colegiado UNIQUE (no_colegiado),
    CONSTRAINT ck_medico_colegiado CHECK (length(trim(no_colegiado)) >= 3),  -- numero de colegiado activo valido
    CONSTRAINT ck_medico_condicion CHECK (condicion IN ('Planta', 'Residente', 'Interno', 'Externo')),  -- condicion laboral de contratacion del facultativo
    CONSTRAINT ck_medico_tarifa    CHECK (tarifa_consulta >= 0),  -- honorario de consulta medica no negativo
    CONSTRAINT ck_medico_externo   CHECK ((condicion = 'Externo' AND institucion_origen IS NOT NULL) OR (condicion <> 'Externo' AND institucion_origen IS NULL)),  -- institucion de procedencia obligatoria exclusivamente para medicos externos
    CONSTRAINT fk_medico_personal FOREIGN KEY (id_personal)
        REFERENCES personal (id_personal) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Especialidades acreditadas de cada médico dentro del hospital (N:M).
CREATE TABLE medico_especialidad (
    id_medico       INTEGER NOT NULL,
    id_especialidad INTEGER NOT NULL,
    es_principal    BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_medico_especialidad PRIMARY KEY (id_medico, id_especialidad),
    CONSTRAINT fk_medesp_medico FOREIGN KEY (id_medico)
        REFERENCES medico (id_personal) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_medesp_especialidad FOREIGN KEY (id_especialidad)
        REFERENCES especialidad (id_especialidad) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Asignación operativa de personal a unidades hospitalarias y turnos de trabajo.
CREATE TABLE asignacion_personal (
    id_asignacion      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_personal        INTEGER NOT NULL,
    id_unidad_hospital INTEGER NOT NULL,
    id_turno           INTEGER NOT NULL,
    fecha_inicio       DATE    NOT NULL,
    fecha_fin          DATE,
    CONSTRAINT pk_asignacion_personal PRIMARY KEY (id_asignacion),
    CONSTRAINT uq_asignacion_personal UNIQUE (id_personal, id_unidad_hospital, id_turno, fecha_inicio),
    CONSTRAINT ck_asignacion_fechas   CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),  -- vigencia de asignacion coherente sin fin anterior al inicio
    CONSTRAINT fk_asignacion_personal FOREIGN KEY (id_personal)
        REFERENCES personal (id_personal) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_asignacion_unidad FOREIGN KEY (id_unidad_hospital)
        REFERENCES unidad_hospital (id_unidad_hospital) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_asignacion_turno FOREIGN KEY (id_turno)
        REFERENCES turno (id_turno) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Horario semanal de atención ambulatoria de cada médico en clínica matutina.
CREATE TABLE horario_medico (
    id_horario  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_medico   INTEGER  NOT NULL,
    id_clinica  INTEGER  NOT NULL,
    dia_semana  SMALLINT NOT NULL,
    hora_inicio TIME     NOT NULL,
    hora_fin    TIME     NOT NULL,
    CONSTRAINT pk_horario_medico   PRIMARY KEY (id_horario),
    CONSTRAINT uq_horario_medico   UNIQUE (id_medico, id_clinica, dia_semana, hora_inicio),
