-- Cirugía programada o ejecutada en quirófano con control de tiempos y no traslape.
CREATE TABLE cirugia (
    id_cirugia           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud_cirugia BIGINT      NOT NULL,
    id_quirofano         INTEGER     NOT NULL,
    inicio_programado    TIMESTAMPTZ NOT NULL,
    fin_programado       TIMESTAMPTZ NOT NULL,
    inicio_real          TIMESTAMPTZ,
    fin_real             TIMESTAMPTZ,
    estado               VARCHAR(10) NOT NULL DEFAULT 'Programada',
    id_ingreso           BIGINT,
    condicion_evolucion  VARCHAR(20),
    CONSTRAINT pk_cirugia              PRIMARY KEY (id_cirugia),
    CONSTRAINT uq_cirugia_solicitud    UNIQUE (id_solicitud_cirugia),
    CONSTRAINT ck_cirugia_estado       CHECK (estado IN ('Programada', 'En curso', 'Finalizada', 'Cancelada')),  -- ciclo de estado de la operacion
    CONSTRAINT ck_cirugia_programada   CHECK (fin_programado > inicio_programado),  -- fin programado cronologicamente posterior al inicio
    CONSTRAINT ck_cirugia_real         CHECK (fin_real IS NULL OR (inicio_real IS NOT NULL AND fin_real > inicio_real)),  -- fin real coherente con inicio real registrado
    CONSTRAINT ck_cirugia_evolucion    CHECK (condicion_evolucion IS NULL OR condicion_evolucion IN ('Sin complicaciones', 'Complicaciones', 'Complicaciones graves')),  -- condiciones de evolucion del acto quirurgico
    CONSTRAINT ck_cirugia_evolucion_est CHECK (condicion_evolucion IS NULL OR estado = 'Finalizada'),  -- evolucion transitoria consignable exclusivamente al finalizar
    -- Restricción de exclusión GiST: impide solapes de cirugías activas en el mismo quirófano
    CONSTRAINT ex_cirugia_traslape     EXCLUDE USING gist (
        id_quirofano WITH =,
        (tstzrange(inicio_programado, fin_programado)) WITH &&
    ) WHERE (estado <> 'Cancelada'),  -- exclusion de solapes temporales por quirofano
    CONSTRAINT fk_cirugia_solicitud FOREIGN KEY (id_solicitud_cirugia)
        REFERENCES solicitud_cirugia (id_solicitud_cirugia) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cirugia_quirofano FOREIGN KEY (id_quirofano)
        REFERENCES espacio_atencion (id_espacio) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cirugia_ingreso FOREIGN KEY (id_ingreso)
        REFERENCES ingreso (id_ingreso) ON DELETE RESTRICT ON UPDATE CASCADE
);

