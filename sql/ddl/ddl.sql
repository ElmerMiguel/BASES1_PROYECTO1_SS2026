-- 1. Regla: La fecha de nacimiento no puede ser posterior a la fecha actual.
CREATE OR REPLACE FUNCTION fn_check_persona_fecha_nacimiento()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.fecha_nacimiento > CURRENT_DATE THEN
        RAISE EXCEPTION 'Regla de Negocio Violada: La fecha de nacimiento (%) no puede ser futura.',
            NEW.fecha_nacimiento;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

