    CONSTRAINT fk_cita_anterior FOREIGN KEY (id_cita_anterior)
        REFERENCES cita (id_cita) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_cita_recargo_origen FOREIGN KEY (id_cita_recargo_origen)
        REFERENCES cita (id_cita) ON DELETE SET NULL ON UPDATE CASCADE
);

