    CONSTRAINT ck_cita_cancelacion_aviso CHECK (estado <> 'Cancelada' OR cancelacion_notificada IS NOT NULL),  -- registro obligatorio sobre si la cancelacion fue notificada con anticipacion
    CONSTRAINT fk_cita_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cita_medico FOREIGN KEY (id_medico)
        REFERENCES medico (id_personal) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cita_clinica FOREIGN KEY (id_clinica)
        REFERENCES clinica (id_clinica) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cita_hospital_referente FOREIGN KEY (id_hospital_referente)
